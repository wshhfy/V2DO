import 'package:flutter/material.dart' as m;

class UiLanguage {
  static String current = 'zh';
}

String uiTr(m.BuildContext context, String value) {
  m.Localizations.maybeLocaleOf(context);
  return uiTranslate(value);
}

String uiTranslate(String value) {
  if (UiLanguage.current != 'en') return value;
  final exact = _en[value];
  if (exact != null) return exact;
  final parts = <(RegExp, String Function(RegExpMatch))>[
    (RegExp(r'^(\d+)\s*秒前$'), (m) => '${m[1]} sec ago'),
    (RegExp(r'^(\d+)\s*分钟前$'), (m) => '${m[1]} min ago'),
    (RegExp(r'^(\d+)\s*小时前$'), (m) => '${m[1]} hr ago'),
    (RegExp(r'^(\d+)\s*天前$'), (m) => '${m[1]} days ago'),
    (RegExp(r'^回复 · (\d+)$'), (m) => 'Replies · ${m[1]}'),
    (
      RegExp(r'^正在回复 @(.+) · #(\d+)$'),
      (m) => 'Replying to @${m[1]} · #${m[2]}'
    ),
    (RegExp(r'^回复 (.+)$'), (m) => 'Reply to ${m[1]}'),
    (RegExp(r'^消息 · (\d+) 条未读$'), (m) => 'Notifications · ${m[1]} unread'),
    (RegExp(r'^网站返回 (\d+)$'), (m) => 'Website returned ${m[1]}'),
    (RegExp(r'^(.+) · 发帖$'), (m) => '${m[1]} · New topic'),
    (RegExp(r'^(.+) · 登录与验证$'), (m) => '${m[1]} · Sign in and verify'),
    (RegExp(r'^(.+) · 已登录$'), (m) => '${m[1]} · Signed in'),
    (RegExp(r'^退出 (.+)$'), (m) => 'Sign out of ${m[1]}'),
    (RegExp(r'^已退出 (.+)$'), (m) => 'Signed out of ${m[1]}'),
    (RegExp(r'^(.+) 搜索$'), (m) => 'Search ${m[1]}'),
    (RegExp(r'^(.+) · 最近访问$'), (m) => '${m[1]} · Recent history'),
    (RegExp(r'^(\d+) 条回复$'), (m) => '${m[1]} replies'),
    (RegExp(r'^余额 (.+)$'), (m) => 'Balance ${m[1]}'),
    (RegExp(r'^赞同 (\d+)$'), (m) => 'Upvotes ${m[1]}'),
    (RegExp(r'^正在下载 (.+)，请稍候…$'), (m) => 'Downloading ${m[1]}…'),
    (
      RegExp(r'^正在加载全部回复以确保顺序和筛选完整，已加载 (\d+) 条$'),
      (m) => 'Loading all replies for sorting and filtering · ${m[1]} loaded'
    ),
    (
      RegExp(r'^上传到 (.+)，成功后插入草稿。\n(.+) MB$'),
      (m) => 'Upload to ${m[1]} and insert into your draft.\n${m[2]} MB'
    ),
    (
      RegExp(r'^将发布到 (.+)：\n([\s\S]+)$'),
      (m) =>
          'Post to ${m[1]}:\n${m[2]!.replaceAll('V2EX 发帖可能消耗铜币，以网站规则为准。', 'Posting on V2EX may cost copper coins.')}'
    ),
    (
      RegExp(r'^已打开主题，但已读状态同步失败：(.+)$'),
      (m) => 'Topic opened, but read status could not be synced: ${m[1]}'
    ),
    (RegExp(r'^退出失败：(.+)$'), (m) => 'Sign-out failed: ${m[1]}'),
    (RegExp(r'^版本 (.+)$'), (m) => 'Version ${m[1]}'),
    (
      RegExp(r'^当前版本 (.+) · GitHub Releases$'),
      (m) => 'Version ${m[1]} · GitHub Releases'
    ),
    (
      RegExp(r'^当前版本 (.+) · 尚未配置发布仓库$'),
      (m) => 'Version ${m[1]} · No release repository configured'
    ),
    (RegExp(r'^发现新版本 (.+)$'), (m) => 'New version ${m[1]}'),
  ];
  for (final (pattern, format) in parts) {
    final match = pattern.firstMatch(value);
    if (match != null) return format(match);
  }
  return value;
}

class UiText extends m.Text {
  const UiText(super.data,
      {super.key,
      super.style,
      super.strutStyle,
      super.textAlign,
      super.textDirection,
      super.locale,
      super.softWrap,
      super.overflow,
      super.textScaler,
      super.maxLines,
      super.semanticsLabel,
      super.semanticsIdentifier,
      super.textWidthBasis,
      super.textHeightBehavior,
      super.selectionColor});

  @override
  m.Widget build(m.BuildContext context) {
    m.Localizations.maybeLocaleOf(
        context); // Rebuild when the app locale changes.
    final translated = uiTranslate(data ?? '');
    if (translated == data) return super.build(context);
    return m.Text(translated,
        style: style,
        strutStyle: strutStyle,
        textAlign: textAlign,
        textDirection: textDirection,
        locale: locale,
        softWrap: softWrap,
        overflow: overflow,
        textScaler: textScaler,
        maxLines: maxLines,
        semanticsLabel: semanticsLabel,
        semanticsIdentifier: semanticsIdentifier,
        textWidthBasis: textWidthBasis,
        textHeightBehavior: textHeightBehavior,
        selectionColor: selectionColor);
  }
}

